"""Writes the launcher icon's foreground: a planetarium. A panelled dome on its base, the path
of a planet arching over it, and a few stars.

    python tools/make_icon.py
"""
import math
import os

RES = os.path.join(os.path.dirname(__file__), '..', 'app', 'src', 'main', 'res', 'drawable')
# Adaptive icons are 108 x 108; only the middle 66 x 66 is safe from the launcher's mask.
CX = 54.0
BASE_Y = 69.0            # where the dome meets its base
DOME = 23.0              # dome radius
# Meridians of the dome as seen from the side: half-widths of the ellipses they project to.
MERIDIANS = [0.0, 9.5, 17.5, DOME]
# Panels from the lit left edge to the shaded right edge, in muted rose.
PANELS = ['#F4AFA4', '#EE9A92', '#E48781', '#D97478', '#CB636D', '#BB5464']
BASE_TOP, BASE_SIDE = '#A9495B', '#8C3B50'
ORBIT = '#B9A9E6'
PLANET, STAR = '#F6DDA0', '#F3EEFF'


def path(color, data):
    return '    <path android:fillColor="%s" android:pathData="%s" />' % (color, data)


def panel(inner, outer, side, color):
    """The strip of dome between two meridians; side is -1 (left) or 1 (right)."""
    apex = BASE_Y - DOME
    sweep_out, sweep_back = (1, 0) if side > 0 else (0, 1)
    d = 'M%.2f,%.2f' % (CX, apex)
    d += 'A%.2f,%.2f 0 0 %d %.2f,%.2f' % (outer, DOME, sweep_out, CX + side * outer, BASE_Y)
    d += 'L%.2f,%.2f' % (CX + side * inner, BASE_Y)
    if inner > 0:
        d += 'A%.2f,%.2f 0 0 %d %.2f,%.2f' % (inner, DOME, sweep_back, CX, apex)
    return path(color, d + 'Z')


def sparkle(x, y, size, color):
    """A four-pointed star with pinched sides."""
    d = 'M%.2f,%.2f' % (x, y - size)
    for px, py in ((x + size, y), (x, y + size), (x - size, y), (x, y - size)):
        d += 'Q%.2f,%.2f %.2f,%.2f' % (x, y, px, py)
    return path(color, d + 'Z')


def main():
    paths = []

    # The planet's path: most of a circle arching over the dome, ending short of the base.
    ox, oy, radius = CX, 56.0, 31.0

    def on_orbit(deg):
        a = math.radians(deg)
        return ox + radius * math.sin(a), oy - radius * math.cos(a)

    x0, y0 = on_orbit(-98)
    x1, y1 = on_orbit(98)
    paths.append('    <path android:strokeColor="%s" android:strokeWidth="1.3" android:strokeLineCap="round"'
                 ' android:strokeAlpha="0.75" android:pathData="M%.2f,%.2fA%.2f,%.2f 0 1 1 %.2f,%.2f" />'
                 % (ORBIT, x0, y0, radius, radius, x1, y1))
    px, py = on_orbit(42)
    paths.append(path(PLANET, 'M%.2f,%.2fm-3.4,0a3.4,3.4 0 1 1 6.8,0a3.4,3.4 0 1 1 -6.8,0' % (px, py)))

    # Stars inside the arc.
    for x, y, size in ((38.5, 36.0, 4.2), (57.5, 31.5, 2.6), (69.0, 45.0, 2.0), (31.0, 50.0, 1.8)):
        paths.append(sparkle(x, y, size, STAR))

    # The dome, panel by panel from left to right.
    strips = [(MERIDIANS[i], MERIDIANS[i + 1]) for i in range(len(MERIDIANS) - 1)]
    order = [(-1, s) for s in reversed(strips)] + [(1, s) for s in strips]
    for color, (side, (inner, outer)) in zip(PANELS, order):
        paths.append(panel(inner, outer, side, color))

    # Its base: a low drum, a little wider than the dome, with a darker foot.
    w = DOME + 2.5
    paths.append(path(BASE_TOP, 'M%.2f,%.2fh%.2fv4.5h-%.2fz' % (CX - w, BASE_Y + 0.8, 2 * w, 2 * w)))
    paths.append(path(BASE_SIDE, 'M%.2f,%.2fh%.2fv2.6h-%.2fz' % (CX - w - 1, BASE_Y + 5.3, 2 * w + 2, 2 * w + 2)))

    xml = ('<?xml version="1.0" encoding="utf-8"?>\n'
           '<!-- Generated by tools/make_icon.py -->\n'
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
           '    android:width="108dp"\n    android:height="108dp"\n'
           '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
           + '\n'.join(paths) + '\n</vector>\n')
    with open(os.path.join(RES, 'ic_launcher_foreground.xml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(xml)
    print('wrote ic_launcher_foreground.xml with', len(paths), 'shapes')


if __name__ == '__main__':
    main()
